/** npm run seed: rewrites src/core/seed.ts with every pool known today. */
import { writeFileSync } from 'node:fs';
import { MAINNET } from '../core/config.ts';
import { Indexer } from '../core/indexer.ts';
import { LAUNCH_CREATED, PADS } from '../core/venues/gnomi.ts';
import { decodePool, POOL_CREATED } from '../core/venues/gnoswap.ts';

const ix = new Indexer(MAINNET.indexer), height = await ix.latestHeight(), pools = (await ix.eventsAfter(POOL_CREATED, 0)).map(decodePool).filter((p) => p.height <= height);
const launches = (await Promise.all(PADS.map(async (pad) => (await ix.eventsAfter(LAUNCH_CREATED(pad), 0)).map((e) => [`${pad}:${e.attrs['id']}`, e.height] as const)))).flat();
const rows = pools.map((p) => `    { path: '${p.path}', token0: '${p.token0}', token1: '${p.token1}', fee: ${p.fee}, height: ${p.height}, sqrtPriceX96: ${p.sqrtPriceX96}n },`).join('\n');
writeFileSync(new URL('../core/seed.ts', import.meta.url), `import type { PoolInfo } from './venues/gnoswap.ts';

export interface PoolSeed { height: number; pools: readonly PoolInfo[] }

/** Generated by \`npm run seed\`. Pools are permanent; newer ones are scanned from \`height\`. */
export const SEED: PoolSeed = {
  height: ${height},
  pools: [
${rows}
  ],
};

/** Creation block of each known launch. */
export const LAUNCHES: Record<string, number> = {
${launches.map(([k, h]) => `  '${k}': ${h},`).join('\n')}
};
`);
console.log(`${pools.length} pools and ${launches.length} launches up to block ${height}`);
